"""Train MesoNet (Meso-4 / MesoInception-4) on CASIA v2.0 and DFDC.

Expected folder layout (you can point --data_dir at any root):

    datasets/
      casia/
        real/   <- authentic images (from CASIA v2.0 Au split)
        fake/   <- spliced/doctored images (CASIA v2.0 Tp split)
      dfdc/
        real/
        fake/
      celebdf/      <- generated by prepare_celebdf.py
        real/
        fake/

Run:
    python train_mesonet.py --data_dir datasets --epochs 20 --arch meso4

The best checkpoint is saved to checkpoints/mesonet.pth and is then
automatically picked up by inference_2.py (ensembled with EfficientNet).
"""

import argparse
import os
import glob

import cv2
import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader, random_split

from models.mesonet import Meso4, MesoInception4

IMG_EXTS = ('.jpg', '.jpeg', '.png', '.bmp', '.webp')


class FaceImageDataset(Dataset):
    """Loads real/fake images from any dataset folder (casia, dfdc, ...)."""

    def __init__(self, root, size=256):
        self.samples = []
        self.size = size
        for ds in os.listdir(root):
            for label_name, label in (("real", 0), ("fake", 1)):
                folder = os.path.join(root, ds, label_name)
                if not os.path.isdir(folder):
                    continue
                for path in glob.glob(os.path.join(folder, "**", "*"), recursive=True):
                    if path.lower().endswith(IMG_EXTS):
                        self.samples.append((path, label))
        if not self.samples:
            raise RuntimeError(f"No images found under {root}/<dataset>/<real|fake>")
        print(f"[data] {len(self.samples)} images found under {root}")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        path, label = self.samples[idx]
        img = cv2.imread(path)
        if img is None:
            img = np.zeros((self.size, self.size, 3), np.uint8)
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
        img = cv2.resize(img, (self.size, self.size)).astype(np.float32) / 255.0
        tensor = torch.from_numpy(img.transpose(2, 0, 1))
        return tensor, torch.tensor([float(label)], dtype=torch.float32)


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--data_dir', default='datasets')
    p.add_argument('--epochs', type=int, default=20)
    p.add_argument('--batch_size', type=int, default=16)
    p.add_argument('--lr', type=float, default=1e-4)
    p.add_argument('--arch', default='meso4', choices=['meso4', 'mesoinception4'])
    p.add_argument('--out', default='checkpoints/mesonet.pth')
    args = p.parse_args()

    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    print(f"[train] device: {device}")

    dataset = FaceImageDataset(args.data_dir)
    n_val = max(1, int(0.2 * len(dataset)))
    train_ds, val_ds = random_split(dataset, [len(dataset) - n_val, n_val])
    train_dl = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True, num_workers=0)
    val_dl = DataLoader(val_ds, batch_size=args.batch_size, num_workers=0)

    model = Meso4() if args.arch == 'meso4' else MesoInception4()
    model.to(device)
    opt = torch.optim.Adam(model.parameters(), lr=args.lr)
    criterion = nn.BCELoss()

    best_acc = 0.0
    for epoch in range(1, args.epochs + 1):
        model.train()
        total_loss = 0.0
        for x, y in train_dl:
            x, y = x.to(device), y.to(device)
            opt.zero_grad()
            out = model(x)
            loss = criterion(out, y)
            loss.backward()
            opt.step()
            total_loss += loss.item()

        model.eval()
        correct = total = 0
        with torch.no_grad():
            for x, y in val_dl:
                x, y = x.to(device), y.to(device)
                pred = (model(x) > 0.5).float()
                correct += (pred == y).sum().item()
                total += y.numel()
        acc = correct / max(total, 1)
        print(f"[epoch {epoch}/{args.epochs}] loss={total_loss:.4f} val_acc={acc:.4f}")

        if acc >= best_acc:
            best_acc = acc
            os.makedirs(os.path.dirname(args.out), exist_ok=True)
            torch.save({'state_dict': model.state_dict(), 'arch': args.arch}, args.out)
            print(f"  -> saved best model to {args.out} (acc={acc:.4f})")

    print(f"[done] best val accuracy: {best_acc:.4f}")


if __name__ == '__main__':
    main()
